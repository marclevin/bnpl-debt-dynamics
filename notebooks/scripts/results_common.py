def arm(df: pd.DataFrame, label: str) -> pd.DataFrame:
    out = df[df.label == label]
    if out.empty:
        raise KeyError(f"no arm labelled {label!r}")
    return out


def years(df: pd.DataFrame) -> float:
    """Post-burn-in horizon in years, over which cumulative quantities are summed."""
    post = (df.n_ticks - df.burn_in).unique()
    assert len(post) == 1, post
    return float(post[0]) * TICK_DAYS / 365.0


def ms(x: pd.Series) -> tuple[float, float, float]:
    """mean, replicate sd, standard error of the mean."""
    x = pd.Series(x, dtype=float)
    return float(x.mean()), float(x.std(ddof=1)), float(x.std(ddof=1) / math.sqrt(len(x)))


def diff(a: pd.Series, b: pd.Series) -> tuple[float, float]:
    """a - b with one unpaired standard error."""
    ma, sa, _ = ms(a)
    mb, sb, _ = ms(b)
    return ma - mb, math.sqrt(sa**2 / len(a) + sb**2 / len(b))


def shares_seeds(a: pd.DataFrame, b: pd.DataFrame) -> bool:
    """Whether two arms form a valid pairing: the same seeds AND the same population.

    A seed fixes the population sample as well as the random stream, so arms of different
    population size share seed numbers without sharing anything that pairs them.
    """
    same_seeds = len(a) == len(b) and set(a.seed) == set(b.seed) and a.seed.is_unique
    same_population = set(a.n_agents) == set(b.n_agents)
    return same_seeds and same_population


def delta(a: pd.DataFrame, b: pd.DataFrame, col) -> tuple[float, float]:
    """a - b on `col`: paired by seed when the two arms share seeds, unpaired otherwise.

    `col` is a column name or a function of an arm that returns a per-replicate series.
    """
    fa = (lambda d: d[col]) if isinstance(col, str) else col
    if shares_seeds(a, b):
        x = pd.Series(fa(a).to_numpy(dtype=float), index=a.seed.to_numpy())
        y = pd.Series(fa(b).to_numpy(dtype=float), index=b.seed.to_numpy())
        d = x - y.reindex(x.index)
        return float(d.mean()), float(d.std(ddof=1) / math.sqrt(len(d)))
    return diff(fa(a), fa(b))


def ratio_change(a: pd.DataFrame, b: pd.DataFrame, col: str) -> tuple[float, float]:
    """mean(a)/mean(b) - 1 with a delta-method standard error (paired when seeds are shared)."""
    d, se = delta(a, b, col)
    mb = float(b[col].mean())
    return d / mb, se / mb


def detectable(d: float, se: float) -> bool:
    """The thesis convention: a difference beyond two standard errors."""
    return abs(d) > 2.0 * se


def paired_diff(a: pd.DataFrame, b: pd.DataFrame, col: str) -> tuple[float, float]:
    """a - b on matched seeds, with the paired standard error."""
    x = a.set_index("seed")[col]
    y = b.set_index("seed")[col]
    assert set(x.index) == set(y.index), "paired arms must share seeds"
    d = (x - y.reindex(x.index)).astype(float)
    return float(d.mean()), float(d.std(ddof=1) / math.sqrt(len(d)))


# ------------------------------------------------------------------ formatting
def pct(x: float, d: int = 2) -> str:
    return f"{x * 100:.{d}f}"


def signed(x: float, d: int = 2) -> str:
    """x with an explicit sign and thousands separators, except a value that rounds to zero,
    which prints as 0.00 with no sign (never -0.00 or +0.00)."""
    s = f"{x:+,.{d}f}".replace(",", "{,}")
    return s[1:] if float(f"{x:.{d}f}") == 0 else s


def cell(x: pd.Series, d: int = 2, scale: float = 100.0) -> str:
    """'mean (sd)' for a replicate series, both scaled (per cent by default)."""
    m, s, _ = ms(x)
    return f"{num(m * scale, d)} ({num(s * scale, d)})"


def pm(d: float, se: float, dd: int = 2, scale: float = 100.0, unit: str = "") -> str:
    return f"${signed(d * scale, dd)} \\pm {num(se * scale, dd)}${unit}"


def pmb(d: float, se: float, dd: int = 2, scale: float = 100.0) -> str:
    """As `pm`, in bold where the difference exceeds two standard errors (Section 3.1)."""
    body = f"{signed(d * scale, dd)} \\pm {num(se * scale, dd)}"
    return f"$\\boldsymbol{{{body}}}$" if detectable(d, se) else f"${body}$"


def param(x: float, d: int = 2) -> str:
    """A parameter value at two decimals, or more where two would lose a digit (0.025)."""
    while d < 6 and abs(float(f"{x:.{d}f}") - x) > 1e-12:
        d += 1
    return f"{x:.{d}f}"


def rand(x: float, d: int = 0) -> str:
    return "R" + f"{x:,.{d}f}".replace(",", "{,}")


def rm(x: float, d: int = 2) -> str:
    """Rand millions."""
    return f"{x / 1e6:.{d}f}"


def num(x: float, d: int = 0) -> str:
    return f"{x:,.{d}f}".replace(",", "{,}")


# ------------------------------------------------------------------ LaTeX table
HEADER = (
    "% GENERATED by notebooks/scripts/build_results_tables.py from results/raw --\n"
    "% do not edit by hand; re-run the script instead.\n"
)


def table(
    name: str,
    caption: str,
    note: str,
    colspec: str,
    header: str,
    rows: list[str],
    size: str = r"\small",
    colsep: str = "4pt",
    placement: str = "H",
) -> None:
    body = "\n".join(rows)
    tex = (
        HEADER
        + f"\\begin{{table}}[{placement}]\n\\centering\n"
        + f"\\caption{{{caption}}}\n\\label{{tab:{name.replace('tab_', '').replace('_', '-')}}}\n"
        + f"\\tabnote{{{note}}}\n"
        + f"\\begingroup\\setlength{{\\tabcolsep}}{{{colsep}}}{size}\n"
        + f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n"
        + body
        + "\n\\bottomrule\n\\end{tabular}\n\\endgroup\n\\end{table}\n"
    )
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / f"{name}.tex").write_text(tex, encoding="utf-8")
    print(f"wrote thesis/chapters/generated/{name}.tex")


def group_row(title: str, ncols: int) -> str:
    return f"\\multicolumn{{{ncols}}}{{l}}{{\\emph{{{title}}}}} \\\\"


