def load(name: str) -> pd.DataFrame:
    return pd.read_parquet(RAW / f"{name}.parquet")


def arm(df: pd.DataFrame, label: str) -> pd.DataFrame:
    out = df[df.label == label]
    if out.empty:
        raise KeyError(f"no arm labelled {label!r}")
    return out


def years(df: pd.DataFrame) -> float:
    """Post-burn-in horizon in years, over which cumulative quantities are summed."""
    post = (df.n_ticks - df.burn_in).unique()
    assert len(post) == 1, post
    return float(post[0]) * TICK_DAYS / 365.0


def ms(x: pd.Series) -> tuple[float, float, float]:
    """mean, replicate sd, standard error of the mean."""
    x = pd.Series(x, dtype=float)
    return float(x.mean()), float(x.std(ddof=1)), float(x.std(ddof=1) / math.sqrt(len(x)))


def diff(a: pd.Series, b: pd.Series) -> tuple[float, float]:
    """a - b with one unpaired standard error."""
    ma, sa, _ = ms(a)
    mb, sb, _ = ms(b)
    return ma - mb, math.sqrt(sa**2 / len(a) + sb**2 / len(b))


def paired_diff(a: pd.DataFrame, b: pd.DataFrame, col: str) -> tuple[float, float]:
    """a - b on matched seeds, with the paired standard error."""
    x = a.set_index("seed")[col]
    y = b.set_index("seed")[col]
    assert set(x.index) == set(y.index), "paired arms must share seeds"
    d = (x - y.reindex(x.index)).astype(float)
    return float(d.mean()), float(d.std(ddof=1) / math.sqrt(len(d)))


# ------------------------------------------------------------------ formatting
def pct(x: float, d: int = 2) -> str:
    return f"{x * 100:.{d}f}"


def cell(x: pd.Series, d: int = 2, scale: float = 100.0) -> str:
    """'mean (sd)' for a replicate series, both scaled (per cent by default)."""
    m, s, _ = ms(x)
    return f"{m * scale:.{d}f} ({s * scale:.{d}f})"


def pm(d: float, se: float, dd: int = 2, scale: float = 100.0, unit: str = "") -> str:
    return f"${d * scale:+.{dd}f} \\pm {se * scale:.{dd}f}${unit}"


def rand(x: float, d: int = 0) -> str:
    return "R" + f"{x:,.{d}f}".replace(",", "{,}")


def rm(x: float, d: int = 2) -> str:
    """Rand millions."""
    return f"{x / 1e6:.{d}f}"


def num(x: float, d: int = 0) -> str:
    return f"{x:,.{d}f}".replace(",", "{,}")


# ------------------------------------------------------------------ LaTeX table
HEADER = (
    "% GENERATED by notebooks/scripts/build_results_tables.py from results/raw --\n"
    "% do not edit by hand; re-run the script instead.\n"
)


def table(
    name: str,
    caption: str,
    note: str,
    colspec: str,
    header: str,
    rows: list[str],
    size: str = r"\small",
    colsep: str = "4pt",
    placement: str = "H",
) -> None:
    body = "\n".join(rows)
    tex = (
        HEADER
        + f"\\begin{{table}}[{placement}]\n\\centering\n"
        + f"\\caption{{{caption}}}\n\\label{{tab:{name.replace('tab_', '').replace('_', '-')}}}\n"
        + f"\\tabnote{{{note}}}\n"
        + f"\\begingroup\\setlength{{\\tabcolsep}}{{{colsep}}}{size}\n"
        + f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n"
        + body
        + "\n\\bottomrule\n\\end{tabular}\n\\endgroup\n\\end{table}\n"
    )
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / f"{name}.tex").write_text(tex, encoding="utf-8")
    print(f"wrote thesis/chapters/generated/{name}.tex")


def group_row(title: str, ncols: int) -> str:
    return f"\\multicolumn{{{ncols}}}{{l}}{{\\emph{{{title}}}}} \\\\"


